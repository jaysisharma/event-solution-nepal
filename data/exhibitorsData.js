export function getEventBySlug(slug) {
    return EXHIBITOR_EVENTS.find((e) => e.slug === slug || e.id === slug);
}

export function getEditionData(eventSlug, year) {
    const event = getEventBySlug(eventSlug);
    if (!event) return null;
    const edition = event.editions.find((ed) => ed.year === year);
    if (!edition) return null;

    const exhibitorsWithLogos = (edition.exhibitors || []).map((ex, idx) => ({
        ...ex,
        logo: ex.logo || COMPANY_LOGOS[idx % COMPANY_LOGOS.length]
    }));

    return {
        event,
        edition: {
            ...edition,
            exhibitors: exhibitorsWithLogos
        }
    };
}

export function getExhibitorData(eventSlug, year, exhibitorId) {
    const data = getEditionData(eventSlug, year);
    if (!data) return null;
    const exhibitor = data.edition.exhibitors?.find((ex) => ex.id === exhibitorId);
    if (!exhibitor) return null;
    return { event: data.event, edition: data.edition, exhibitor };
}
